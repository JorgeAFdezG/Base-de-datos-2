/*PROCEDIMIENTO 2 - Luis
 * Crea un procedimiento que, dado un ID_EMPLEADO, muestre su nombre completo y los turnos en los que ha trabajado, ordenados por fecha de inicio.*/
CREATE OR REPLACE PROCEDURE PROYECTOFINAL.PRC_MOSTRAR_TURNOS_EMPLEADO (P_ID_EMPLEADO IN NUMBER) AS
  V_NOMBRE_COMPLETO VARCHAR2(300);
  -- Definición del cursor
  CURSOR C_TURNOS IS
    SELECT HORA_INICIO, HORA_FIN
    FROM PROYECTOFINAL.TURNO
    WHERE FK_EMPLEADO = P_ID_EMPLEADO
    ORDER BY HORA_INICIO;
  -- Variables para leer cada fila del cursor
  V_HORA_INICIO PROYECTOFINAL.TURNO.HORA_INICIO%TYPE;
  V_HORA_FIN PROYECTOFINAL.TURNO.HORA_FIN%TYPE;
BEGIN
  -- Obtener nombre completo del empleado
  SELECT NOMBRE || ' ' || APELLIDO_PATERNO || ' ' || APELLIDO_MATERNO
  INTO V_NOMBRE_COMPLETO
  FROM PROYECTOFINAL.EMPLEADO
  WHERE ID_EMPLEADO = P_ID_EMPLEADO;
  DBMS_OUTPUT.PUT_LINE('NOMBRE COMPLETO: ' || V_NOMBRE_COMPLETO);
  DBMS_OUTPUT.PUT_LINE('TURNOS TRABAJADOS:');
  -- Abrir cursor
  OPEN C_TURNOS;
  -- Iterar sobre los resultados del cursor
  LOOP
    FETCH C_TURNOS INTO V_HORA_INICIO, V_HORA_FIN;
    EXIT WHEN C_TURNOS%NOTFOUND;
    DBMS_OUTPUT.PUT_LINE('Inicio: ' || TO_CHAR(V_HORA_INICIO, 'YYYY-MM-DD HH24:MI') ||
                         ' - Fin: ' || TO_CHAR(V_HORA_FIN, 'YYYY-MM-DD HH24:MI'));
  END LOOP;
  -- Cerrar cursor
  CLOSE C_TURNOS;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('NO SE ENCONTRO NINGUN EMPLEADO CON EL ID INTRODUCIDO.');
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('OCURRIO UN ERROR: ' || SQLERRM);
END;

/*CONSULTA PARA SABER LOS TURNOS QUE HA TRABAJADO UN EMPLEADO*/
BEGIN
	PROYECTOFINAL.PRC_MOSTRAR_TURNOS_EMPLEADO(1);
