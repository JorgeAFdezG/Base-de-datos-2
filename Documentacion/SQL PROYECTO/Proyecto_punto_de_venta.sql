CREATE OR REPLACE TRIGGER PROYECTOFINAL.trg_insertar_movimiento_inventario
AFTER INSERT ON PROYECTOFINAL.Detalle_de_venta -- El trigger se dispara después de insertar en Detalle_de_venta
FOR EACH ROW
DECLARE
    maximo_id NUMBER;
    v_fk_sucursal NUMBER; -- Variable para almacenar fk_sucursal
BEGIN
    -- 1. Obtener el próximo ID de INVENTARIO_DE_MOVIMIENTOS
    SELECT NVL(MAX(id_inventario_de_movimientos), 0) + 1
    INTO maximo_id
    FROM PROYECTOFINAL.inventario_de_movimientos;

    -- 2. Obtener fk_sucursal de la tabla CAJA a través de VENTA
    --    Se usa :NEW.fk_venta para enlazar con la venta recién insertada
    SELECT c.fk_sucursal -- inventario_de_movimientos necesita la columna sucursal 
    INTO v_fk_sucursal
    FROM PROYECTOFINAL.Venta v
    INNER JOIN PROYECTOFINAL.caja c ON v.fk_caja = c.id_Caja
    WHERE v.id_Venta = :NEW.fk_venta; -- :NEW.fk_venta es el ID de venta de la fila recién insertada en Detalle_de_venta

    -- 3. Insertar el nuevo movimiento en INVENTARIO_DE_MOVIMIENTOS
    INSERT INTO PROYECTOFINAL.INVENTARIO_DE_MOVIMIENTOS (
        ID_INVENTARIO_DE_MOVIMIENTOS,
        TIPO_MOVIMIENTO,
        CANTIDAD,
        FECHA,
        FK_PRODUCTO,
        FK_SUCURSAL,
        FK_DETALLE_DE_VENTA,
        FK_DETALLES_DE_COMPRA
    )
    VALUES (
        maximo_id,
        'SALIDA',
        :NEW.cantidad,          -- Cantidad de la fila de Detalle_de_venta recién insertada
        SYSDATE,
        :NEW.fk_producto,       -- Producto de la fila de Detalle_de_venta recién insertada
        v_fk_sucursal,          -- Sucursal obtenida de la consulta anterior
        :NEW.id_Detalle_de_venta, -- ID de Detalle_de_venta de la fila recién insertada
        1                       -- Valor fijo, como en tu query original
    );
END;

