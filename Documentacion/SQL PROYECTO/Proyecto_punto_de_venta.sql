CREATE OR REPLACE FUNCTION PROYECTOFINAL.FN_PROMO_ACTIVA (P_ID_PRODUCTO IN NUMBER)
RETURN VARCHAR2
IS
  V_PROMO NUMBER;
BEGIN
  -- Cuenta si hay alguna promoción activa actualmente para el producto
  SELECT COUNT(*)
  INTO V_PROMO
  FROM PROYECTOFINAL.PROMOCION
  WHERE FK_PRODUCTO = P_ID_PRODUCTO
    AND SYSDATE BETWEEN FECHA_INICIO AND FECHA_FIN;
  -- Retorna 'ACTIVA' si hay promociones activas, 'INACTIVA' si no
  RETURN CASE 
	  -- si se requiere que regrese true o false donde dice activa o inactiva se debe de cambiar por true o false y si se requiere
	  -- 1 para activa o 0 para inactiva se debe de cambiar el tipo de dato en el return a int y en donde dice activa cambiarlo 
	  -- por 1 e inactiva por 0
  	WHEN V_PROMO > 0 THEN 'True' ELSE 'False' END;
END;

